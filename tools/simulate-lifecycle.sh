#!/usr/bin/env bash
# 多章全生命周期集成回归（5 章：埋设→推进→回收、新角色建档、终态回退、重复埋设）
# 用法: bash tools/simulate-lifecycle.sh（在仓库根目录或任意位置）
# 设计要点：模拟阶段四「门禁通过后回写时才建档」，验证门禁在累积状态下的真实行为
set +e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CC="node $ROOT/scripts/check-consistency.js"
WORK="$(mktemp -d /tmp/nw-lifecycle.XXXXXX)"
cd "$WORK"
mkdir -p 设定/角色设定/主角 设定/伏笔追踪 设定/地点设定
cat > 设定/角色设定/主角/林山.md <<'EOF'
# 林山
- 发色：黑
- 瞳色：黑
EOF
cat > 状态快照.md <<'EOF'
# 状态快照（截止第1章）

## 角色状态
| 角色 | 等级 | 当前位置 | 状态 | 背包 | 最后出场章 |
|------|------|----------|------|------|-----------|
| 林山 | 炼气三层 | ？ | 健康 | 断锋剑 | 1 |
EOF

PASS=0; FAIL=0
check() {
  local name="$1" expect="$2" actual="$3" out="$4"
  if [ "$expect" = "$actual" ]; then
    PASS=$((PASS+1)); echo "✅ [$name] exit=$actual 符合预期"
  else
    FAIL=$((FAIL+1)); echo "❌ [$name] 期望 exit=$expect 实际=$actual"; echo "$out" | tail -5
  fi
}

echo "===== 第1章：林山出场，埋设 v1，移动 ====="
cat > 第001章.md <<'EOF'
　　林山在青云山后山醒来，断锋剑躺在手边。
---CHANGES---
<!-- 角色状态变化 -->
- **[林山]**：健康→健康 | 心理变化：初入江湖
<!-- 伏笔动作（四态，必须引用伏笔ID） -->
- 🔨埋设 **v1 断锋来历**（类型：长线）| 预期读者效果：揭晓时震惊于铺垫 | 线索：断剑
<!-- 交接包 -->
- 剧情当前位置：觉醒（主线起点）
- 未了结线索：v1
- 关键人物位置：林山@青云山后山
<!-- 角色移动 -->
- **[林山]**：—→青云山后山
---END CHANGES---
EOF
OUT=$($CC 状态快照.md 第001章.md 设定 2>&1); CODE=$?
check "第1章（新书首章埋设v1+移动）" 0 $CODE "$OUT"
# 回写：v1 已埋设 + 建 v1 文档（阶段四「埋设即建档」）
cat > 设定/伏笔追踪/v1-断锋来历.md <<'EOF'
# v1 断锋来历
- 类型：长线
- 预期读者效果：揭晓时震惊于铺垫
EOF
python3 - <<'PY'
s = open('状态快照.md').read()
s = s.replace('# 状态快照（截止第1章）', '# 状态快照（截止第1章）\n\n## 伏笔状态\n| 伏笔ID | 伏笔名 | 类型 | 预期读者效果 | 状态 | 埋设章 | 推进章 | 揭晓章 |\n|--------|--------|------|--------------|------|--------|--------|--------|\n| v1 | 断锋来历 | 长线 | 揭晓时震惊于铺垫 | 已埋设 | 1 | — | 待定 |')
open('状态快照.md','w').write(s)
PY

echo "===== 第2章：苏瑶首登场（未建档应拦；建档后通过），推进 v1 ====="
cat > 第002章.md <<'EOF'
　　林山遇见了苏瑶。她的银发在月光下泛着冷光。
---CHANGES---
<!-- 角色状态变化 -->
- **[林山]**：健康→健康 | 关系变化：与苏瑶信任+1
- **[苏瑶]**：健康→健康
<!-- 伏笔动作（四态，必须引用伏笔ID） -->
- ➡️推进 **v1 断锋来历** | 新线索：苏瑶知道断剑来历
<!-- 交接包 -->
- 剧情当前位置：遇见苏瑶（主线推进）
- 未了结线索：v1
- 关键人物位置：林山@青云山、苏瑶@青云山
<!-- 角色移动 -->
- **[林山]**：青云山后山→青云山
- **[苏瑶]**：天剑宗→青云山
---END CHANGES---
EOF
OUT=$($CC 状态快照.md 第002章.md 设定 2>&1); CODE=$?
check "第2章（苏瑶未建档应拦）" 1 $CODE "$OUT"
grep -q "未登记实体：苏瑶" <<<"$OUT" && echo "  → 拦截原因正确：苏瑶未登记" || { echo "  → 拦截原因不符！"; echo "$OUT"; }
cat > 设定/角色设定/主角/苏瑶.md <<'EOF'
# 苏瑶
- 发色：银白
- 瞳色：蓝
EOF
cat > 设定/地点设定/青云山.md <<'EOF'
# 青云山
EOF
OUT=$($CC 状态快照.md 第002章.md 设定 2>&1); CODE=$?
check "第2章（建档后通过）" 0 $CODE "$OUT"
python3 - <<'PY'
s = open('状态快照.md').read()
s = s.replace('| 林山 | 炼气三层 | ？ | 健康 | 断锋剑 | 1 |', '| 林山 | 炼气三层 | 青云山 | 健康 | 断锋剑 | 2 |')
s = s.replace('| v1 | 断锋来历 | 长线 | 揭晓时震惊于铺垫 | 已埋设 | 1 | — | 待定 |', '| v1 | 断锋来历 | 长线 | 揭晓时震惊于铺垫 | 已推进 | 1 | 2 | 待定 |')
s = s.replace('| 林山 | 炼气三层 | 青云山 | 健康 | 断锋剑 | 2 |', '| 林山 | 炼气三层 | 青云山 | 健康 | 断锋剑 | 2 |\n| 苏瑶 | 筑基期 | 青云山 | 健康 | — | 2 |')
s = s.replace('# 状态快照（截止第1章）', '# 状态快照（截止第2章）')
s = s.replace('## 伏笔状态', '## 角色外貌（用于描写一致性校验）\n| 角色 | 发色 | 瞳色 | 外貌特征 | 性格标签 |\n|------|------|------|----------|----------|\n| 林山 | 黑 | 黑 | 剑眉星目 | 果决 |\n| 苏瑶 | 银白 | 蓝 | 清冷 | 清冷 |\n\n## 伏笔状态')
open('状态快照.md','w').write(s)
PY

echo "===== 第3章：回收 v1，埋设 v2（回写时才建 v2 文档），银发误写应拦 ====="
cat > 第003章.md <<'EOF'
　　古庙里，苏瑶揭开了断锋剑的秘密——剑是掌门所铸，为镇压古庙邪物而断。
　　林山的银发在灯下泛着冷光。
---CHANGES---
<!-- 角色状态变化 -->
- **[林山]**：健康→健康
<!-- 伏笔动作（四态，必须引用伏笔ID） -->
- ✅回收 **v1 断锋来历** | 回收方式：苏瑶揭晓剑为掌门所铸
- 🔨埋设 **v2 古庙邪物**（类型：短线）| 预期读者效果：十章内小惊喜 | 线索：古庙封印
<!-- 交接包 -->
- 剧情当前位置：断剑秘密揭晓（主线推进）
- 未了结线索：v2
- 关键人物位置：林山@古庙、苏瑶@古庙
<!-- 角色移动 -->
- **[林山]**：青云山→古庙
- **[苏瑶]**：青云山→古庙
---END CHANGES---
EOF
OUT=$($CC 状态快照.md 第003章.md 设定 2>&1); CODE=$?
check "第3章（回收v1+埋设v2+林山银发误写应拦）" 1 $CODE "$OUT"
grep -q "林山 正文写「银发」，设定记「黑发」" <<<"$OUT" && echo "  → 拦截原因正确：林山银发 vs 黑发" || { echo "  → 拦截原因不符！"; echo "$OUT" | head -8; }
sed -i 's/林山的银发/林山的黑发/' 第003章.md
mkdir -p 设定/地点设定 && cat > 设定/地点设定/古庙.md <<'EOF'
# 古庙
EOF
OUT=$($CC 状态快照.md 第003章.md 设定 2>&1); CODE=$?
check "第3章（修正后通过，v2 未建档不误拦）" 0 $CODE "$OUT"
python3 - <<'PY'
s = open('状态快照.md').read()
s = s.replace('# 状态快照（截止第2章）', '# 状态快照（截止第3章）')
s = s.replace('| 林山 | 炼气三层 | 青云山 | 健康 | 断锋剑 | 2 |', '| 林山 | 炼气三层 | 古庙 | 健康 | 断锋剑 | 3 |')
s = s.replace('| 苏瑶 | 筑基期 | 青云山 | 健康 | — | 2 |', '| 苏瑶 | 筑基期 | 古庙 | 健康 | — | 3 |')
s = s.replace('| v1 | 断锋来历 | 长线 | 揭晓时震惊于铺垫 | 已推进 | 1 | 2 | 待定 |', '| v1 | 断锋来历 | 长线 | 揭晓时震惊于铺垫 | 已回收 | 1 | 2 | 3 |')
s = s + '| v2 | 古庙邪物 | 短线 | 十章内小惊喜 | 已埋设 | 3 | — | 待定 |\n'
open('状态快照.md','w').write(s)
PY
cat > 设定/伏笔追踪/v2-古庙邪物.md <<'EOF'
# v2 古庙邪物
- 类型：短线
EOF

echo "===== 第4章：终态 v1 再推进应拦；v2 推进 ====="
cat > 第004章.md <<'EOF'
　　林山和苏瑶离开古庙，赶回天剑宗。
---CHANGES---
<!-- 伏笔动作（四态，必须引用伏笔ID） -->
- ➡️推进 **v1 断锋来历** | 又推
- ➡️推进 **v2 古庙邪物** | 封印松动迹象
<!-- 交接包 -->
- 剧情当前位置：返程（支线推进）
- 未了结线索：v2
<!-- 角色移动 -->
- **[林山]**：古庙→天剑宗
- **[苏瑶]**：古庙→天剑宗
---END CHANGES---
EOF
OUT=$($CC 状态快照.md 第004章.md 设定 2>&1); CODE=$?
check "第4章（终态v1再推进应拦）" 1 $CODE "$OUT"
grep -q "已是终态「已回收」" <<<"$OUT" && echo "  → 拦截原因正确：终态回退" || { echo "  → 拦截原因不符！"; echo "$OUT"; }
sed -i '/➡️推进 \*\*v1/d' 第004章.md
OUT=$($CC 状态快照.md 第004章.md 设定 2>&1); CODE=$?
check "第4章（修正后通过）" 0 $CODE "$OUT"
python3 - <<'PY'
s = open('状态快照.md').read()
s = s.replace('# 状态快照（截止第3章）', '# 状态快照（截止第4章）')
s = s.replace('| 林山 | 炼气三层 | 古庙 | 健康 | 断锋剑 | 3 |', '| 林山 | 炼气三层 | 天剑宗 | 健康 | 断锋剑 | 4 |')
s = s.replace('| 苏瑶 | 筑基期 | 古庙 | 健康 | — | 3 |', '| 苏瑶 | 筑基期 | 天剑宗 | 健康 | — | 4 |')
s = s.replace('| v2 | 古庙邪物 | 短线 | 十章内小惊喜 | 已埋设 | 3 | — | 待定 |', '| v2 | 古庙邪物 | 短线 | 十章内小惊喜 | 已推进 | 3 | 4 | 待定 |')
open('状态快照.md','w').write(s)
PY

echo "===== 第5章：v2 再埋设应拦（重复埋设） ====="
cat > 第005章.md <<'EOF'
　　天剑宗内，林山静养。
---CHANGES---
<!-- 角色状态变化 -->
- **[林山]**：健康→健康
<!-- 伏笔动作（四态，必须引用伏笔ID） -->
- 🔨埋设 **v2 古庙邪物**（类型：短线）| 预期读者效果：小惊喜 | 线索：重复
<!-- 交接包 -->
- 剧情当前位置：静养（过渡章）
- 未了结线索：v2
---END CHANGES---
EOF
OUT=$($CC 状态快照.md 第005章.md 设定 2>&1); CODE=$?
check "第5章（重复埋设v2应拦）" 1 $CODE "$OUT"
grep -q "重复埋设：v2 已登记" <<<"$OUT" && echo "  → 拦截原因正确：重复埋设" || { echo "  → 拦截原因不符！"; echo "$OUT"; }

echo ""
echo "===== 结果: PASS=$PASS FAIL=$FAIL ====="
cd / && rm -rf "$WORK"
exit $FAIL
